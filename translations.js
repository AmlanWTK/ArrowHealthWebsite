(function () {
  const STORAGE_KEY = 'arrowhealth_lang';
  let currentLang = localStorage.getItem(STORAGE_KEY) || 'en';

  function applyLanguage(lang, animate) {
    const els = document.querySelectorAll('[data-i18n]');
    const htmlEls = document.querySelectorAll('[data-i18n-html]');
    const dict = TRANSLATIONS[lang];

    function swap() {
      els.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
          el.textContent = dict[key];
        }
      });
      htmlEls.forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (dict[key] !== undefined) {
          el.innerHTML = dict[key];
        }
      });
      document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key] !== undefined) {
          el.setAttribute('placeholder', dict[key]);
        }
      });
      // Update html lang attribute
      document.documentElement.lang = lang === 'bn' ? 'bn' : 'en';
      // Update all toggle buttons (desktop + mobile)
      document.querySelectorAll('.lang-toggle-btn').forEach(function (btnEl) {
        btnEl.textContent = dict['lang-btn'] || (lang === 'en' ? 'BN' : 'EN');
        btnEl.title = dict['lang-btn-label'] || '';
      });
      currentLang = lang;
      localStorage.setItem(STORAGE_KEY, lang);
    }

    if (animate) {
      // Smooth fade out → swap → fade in
      document.body.style.transition = 'opacity 0.28s ease';
      document.body.style.opacity = '0';
      setTimeout(() => {
        swap();
        document.body.style.opacity = '1';
      }, 280);
    } else {
      swap();
    }
  }

  function toggleLang() {
    const newLang = currentLang === 'en' ? 'bn' : 'en';
    applyLanguage(newLang, true);
  }

  // Expose globally so onclick works
  window.arrowToggleLang = toggleLang;

  // Apply on page load (no animation)
  document.addEventListener('DOMContentLoaded', function () {
    applyLanguage(currentLang, false);
  });
})();
